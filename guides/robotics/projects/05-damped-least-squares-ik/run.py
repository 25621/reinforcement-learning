SETTINGS = [
    ("lambda = 0 (plain pseudo-inverse)", dict(lam=0.0)),
    ("lambda = 0.001", dict(lam=1e-3)),
    ("lambda = 0.01", dict(lam=1e-2)),
    ("lambda = 0.05", dict(lam=5e-2)),
    ("lambda = 0.2", dict(lam=2e-1)),
    ("adaptive lambda", dict(adaptive=True)),
    ("lambda = 0.01, clamped to joint limits", dict(lam=1e-2, clamp_limits=True)),
]


