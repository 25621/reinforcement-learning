# 2. The wrist singularity
# ---------------------------------------------------------------------------
def singular_path(robot):
    """A straight Cartesian move that drags the wrist through wrist_2 = 0.

    arm6 has a spherical wrist, and its joints 4 and 6 both turn about their
    own z axis.  When wrist_2 (joint 5) is zero those two axes point the same
    way, so between them they can only produce ONE rotation instead of two:
    the Jacobian loses a rank and one direction of tool rotation vanishes.
    """
    q_a = np.array([0.35, 0.55, -1.10, 0.40, 0.85, 0.20])
    q_b = q_a.copy()
    q_b[4] = -0.85  # sweep wrist_2 from +0.85 to -0.85, straight through 0
    T_a, T_b = fk_all(robot, q_a)["tool0"], fk_all(robot, q_b)["tool0"]
    return q_a, cartesian_lerp(T_a, T_b, 401)


def singularity_study(robot, fname):
    q0, path = singular_path(robot)
    dt = 0.005

    # How close does the path actually come to a singular configuration?
    q_mid = q0.copy()
    q_mid[4] = 0.0
    record("smallest singular value AT wrist_2 = 0",
           float(singular_values(jacobian_analytic(robot, q_mid))[-1]))
    record("smallest singular value at wrist_2 = 0.85",
           float(singular_values(jacobian_analytic(robot, q0))[-1]))

    runs = {}
    for label, kw in [("lambda = 0", dict(lam=0.0)),
                      ("lambda = 0.02", dict(lam=2e-2)),
                      ("lambda = 0.1", dict(lam=1e-1)),
                      ("adaptive", dict(adaptive=True))]:
        _, log = track_path(robot, q0, path, dt, **kw)
        runs[label] = log
        record(f"[{label}] peak joint speed", float(log["qd"].max()), "rad/s")
        record(f"[{label}] mean position error along the path", float(log["err_pos"].mean()), "m")
        record(f"[{label}] worst position error along the path", float(log["err_pos"].max()), "m")
        record(f"[{label}] worst orientation error along the path",
               float(np.degrees(log["err_rot"].max())), "deg")

    t = np.arange(len(runs["lambda = 0"]["qd"])) * dt
    fig, axs = plt.subplots(1, 3, figsize=(9.4, 3.0))
    axs[0].plot(t, runs["lambda = 0.02"]["sigma_min"], color="#333333")
    axs[0].set_yscale("log")
    axs[0].set_xlabel("time along the path (s)")
    axs[0].set_ylabel(r"smallest singular value of $J$")
    axs[0].set_title("the arm passes through a singularity")
    for k, (label, log) in enumerate(runs.items()):
        axs[1].plot(t, log["qd"], color=COLORS[k], label=label)
        axs[2].plot(t, log["err_pos"] * 1e3, color=COLORS[k], label=label)
    axs[1].set_yscale("log")
    axs[1].axhline(3.2, color="#888888", ls="--", lw=1.0)
    axs[1].text(1.25, 3.7, "motor limit 3.2 rad/s", fontsize=7, color="#666666")
    axs[1].set_xlabel("time (s)")
    axs[1].set_ylabel("commanded joint speed (rad/s)")
    axs[1].set_title("undamped, the command explodes")
    axs[1].legend(fontsize=7, loc="lower left")
    axs[2].set_yscale("log")
    axs[2].set_xlabel("time (s)")
    axs[2].set_ylabel("tool position error (mm)")
    axs[2].set_title("damping is paid for in accuracy")
    save(fig, f"{OUT}/singularity.png")
    return runs


def fig_tradeoff(robot, fname):
    """Sweep lambda and plot the two things it trades against each other."""
    q0, path = singular_path(robot)
    dt = 0.005
    lams = np.concatenate([[0.0], np.logspace(-4, -0.3, 16)])
    peak, err = [], []
    for lam in lams:
        _, log = track_path(robot, q0, path, dt, lam=lam)
        peak.append(log["qd"].max())
        err.append(log["err_pos"].mean())
    _, log_ad = track_path(robot, q0, path, dt, adaptive=True)

    # Fair comparison: what does FIXED damping cost at the same peak speed?
    peak, err = np.array(peak), np.array(err)
    ad_peak, ad_err = log_ad["qd"].max(), log_ad["err_pos"].mean()
    same_safety = np.argmin(np.abs(peak - ad_peak))
    # NOTE the honest outcome: this ratio comes out near 1.0, i.e. a fixed
    # lambda tuned for THIS path does just as well.  Adaptive damping's real
    # value is that nobody had to tune it -- see the README.
    record("accuracy ratio, adaptive vs the fixed lambda at the same peak speed (>1 = adaptive better)",
           float(err[same_safety] / ad_err), "x")
    record("the fixed lambda that matches adaptive on peak speed", float(lams[same_safety]))
    record("accuracy ratio, adaptive vs a BADLY chosen fixed lambda (the largest swept)",
           float(err[-1] / ad_err), "x")

    fig, ax = plt.subplots(figsize=(6.2, 3.4))
    sc = ax.scatter(peak, err * 1e3, c=np.log10(np.maximum(lams, 1e-5)),
                    cmap="viridis", s=28, zorder=3)
    ax.plot(peak, err * 1e3, color="#BBBBBB", lw=1.0, zorder=2)
    ax.scatter([ad_peak], [ad_err * 1e3], marker="*", s=200,
               color=COLORS[1], zorder=4, label="adaptive damping")
    ax.axvline(3.2, color="#888888", ls="--", lw=1.0)
    ax.text(3.6, err.min() * 1.5e3, "motor limit", fontsize=7, color="#666666", rotation=90)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("peak commanded joint speed (rad/s)  -- lower is safer")
    ax.set_ylabel("mean tool position error (mm)  -- lower is more accurate")
    ax.set_title("One trade-off curve, and a star that sits ON it:\nadaptive damping matches a hand-tuned lambda without the tuning", fontsize=9)
    fig.colorbar(sc, ax=ax, label=r"$\log_{10}\lambda$")
    ax.legend(fontsize=8, loc="lower left")
    save(fig, f"{OUT}/tradeoff.png")
    record("adaptive: peak joint speed", float(log_ad["qd"].max()), "rad/s")
    record("adaptive: mean position error", float(log_ad["err_pos"].mean() * 1e3), "mm")


# ---------------------------------------------------------------------------
# 3. The solver only cares about the tool
# ---------------------------------------------------------------------------
def posture_drift(robot, n=200, seed=3):
    """Same target, many starts: how different are the arms that get there?

    A 7-joint arm has a whole family of solutions for one tool pose.  Plain IK
    picks whichever member of that family it happened to stumble into, so two
    runs that both 'succeed' can end up in visibly different shapes -- and some
    of them sit hard against a joint limit.  Project 06 is about choosing
    inside that family on purpose.
    """
    rng = np.random.default_rng(seed)
    T = fk_all(robot, robot.random_q(rng))["tool0"]
    sols = []
    for _ in range(n):
        # clamp_limits keeps every solution inside the box the real robot can
        # actually occupy -- without it the solver happily returns joint values
        # of +-100 rad, which are correct arithmetic and impossible hardware.
        q, info = ik(robot, robot.random_q(rng), T, lam=1e-2, max_iters=300, clamp_limits=True)
        if info["ok"]:
            sols.append(q)
    sols = np.array(sols)
    record("solutions found for ONE tool pose", float(len(sols)))
    spread = sols.max(axis=0) - sols.min(axis=0)
    record("widest spread across solutions, over all joints", float(spread.max()), "rad")
    margins = np.array([robot.limit_margin(q).min() for q in sols])
    record("fraction of solutions within 0.1 rad of a joint limit", float((margins < 0.1).mean()))
    record("fraction of solutions AT a joint limit (margin < 1e-6)", float((margins < 1e-6).mean()))

    fig, axs = plt.subplots(1, 2, figsize=(8.4, 3.0))
    for i in range(robot.n):
        axs[0].scatter(np.full(len(sols), i) + rng.normal(0, 0.06, len(sols)), sols[:, i],
                       s=4, alpha=0.35, color=COLORS[0])
        axs[0].plot([i - 0.3, i + 0.3], [robot.lower[i]] * 2, color=COLORS[1], lw=2)
        axs[0].plot([i - 0.3, i + 0.3], [robot.upper[i]] * 2, color=COLORS[1], lw=2)
    axs[0].set_xticks(range(robot.n))
    axs[0].set_xticklabels(robot.joint_names, rotation=35, ha="right", fontsize=7)
    axs[0].set_ylabel("joint value (rad)")
    axs[0].set_title(f"{len(sols)} joint vectors, ONE tool pose\n(orange = joint limits)", fontsize=9)
    axs[1].hist(margins, bins=30, color=COLORS[0])
    axs[1].axvline(0.1, color=COLORS[1], ls="--")
    axs[1].set_xlabel("distance to the nearest joint limit (rad)")
    axs[1].set_ylabel("solutions")
    axs[1].set_title("plain IK does not care how close it parks\nto a limit", fontsize=9)
    save(fig, f"{OUT}/posture_spread.png")
    return sols


def fig_solution_gallery(robot, sols, fname, k=5):
    fig = plt.figure(figsize=(2.0 * k, 2.2))
    idx = np.linspace(0, len(sols) - 1, k).astype(int)
    for i, s in enumerate(idx):
        ax = fig.add_subplot(1, k, i + 1, projection="3d")
        viz.draw_ground(ax, radius=0.45)
        viz.draw_robot(ax, robot, fk_all(robot, sols[s]), show_frames=["tool0"], frame_scale=0.10)
        viz.style_3d(ax, None, radius=0.60, center=(0, 0, 0.46), ticks=False, azim=-58)
    fig.suptitle("Five different arms, one identical tool pose (to 1e-5 m)", y=0.99)
    fig.subplots_adjust(wspace=-0.2, top=0.93, bottom=-0.06, left=0.0, right=1.0)
    save(fig, f"{OUT}/solution_gallery.png")


