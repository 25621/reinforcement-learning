# 1. Convergence over many random targets
# ---------------------------------------------------------------------------
def convergence_study(robot, n=500, seed=0):
    """Targets are generated by forward kinematics, so every one IS reachable.

    That matters: if targets were drawn at random in space, most would be
    unreachable and every solver would 'fail' for a reason that has nothing to
    do with damping.  Generating targets from random joint vectors separates
    'the solver could not find it' from 'there was nothing to find'.
    """
    rng = np.random.default_rng(seed)
    Q_goal = robot.random_q(rng, n)
    Q_start = robot.random_q(rng, n)
    targets = [fk_all(robot, q)["tool0"] for q in Q_goal]

    table = {}
    for label, kw in SETTINGS:
        ok, iters, steps, errs = 0, [], [], []
        for q0, T in zip(Q_start, targets):
            q, info = ik(robot, q0, T, max_iters=200, **kw)
            steps.append(info["max_step"])
            errs.append(info["e_pos"])
            if info["ok"]:
                ok += 1
                iters.append(info["iters"])
        table[label] = {
            "success": ok / n,
            "median_iters": float(np.median(iters)) if iters else float("nan"),
            "median_final_err": float(np.median(errs)),
            "p99_step": float(np.percentile(steps, 99)),
            "max_step": float(np.max(steps)),
        }
        record(f"[{label}] success rate", table[label]["success"])
        record(f"[{label}] median iterations to converge", table[label]["median_iters"])
        record(f"[{label}] 99th-percentile largest joint step", table[label]["p99_step"], "rad")
        record(f"[{label}] largest joint step seen", table[label]["max_step"], "rad")
    return table


def fig_convergence(table, fname):
    labels = list(table)
    fig, axs = plt.subplots(1, 3, figsize=(9.2, 3.0))
    axs[0].barh(labels, [table[k]["success"] for k in labels], color=COLORS[0])
    axs[0].set_xlabel("fraction of 500 targets solved")
    axs[0].set_xlim(0, 1.05)
    axs[0].set_title("did it get there?")
    axs[1].barh(labels, [table[k]["median_iters"] for k in labels], color=COLORS[2])
    axs[1].set_xlabel("median iterations")
    axs[1].set_title("how quickly?")
    axs[1].set_yticklabels([])
    axs[2].barh(labels, [table[k]["max_step"] for k in labels], color=COLORS[1])
    axs[2].set_xscale("log")
    axs[2].set_xlabel("largest single joint step (rad, log)")
    axs[2].set_title("how violently?")
    axs[2].set_yticklabels([])
    axs[2].axvline(np.pi, color="#888888", ls="--", lw=1.0)
    axs[2].text(np.pi * 1.2, -0.4, "half a turn", fontsize=7, color="#666666")
    for ax in axs:
        ax.invert_yaxis()
    fig.suptitle("arm7, 500 reachable targets from random starts: damping costs iterations "
                 "and buys sanity", y=1.04)
    save(fig, f"{OUT}/convergence.png")


